"""Emit paper/tables/tab_dataset.tex from the cached corpora themselves.

Every number is counted from the .pt files the experiments consumed, not copied
from a config, so the table cannot drift away from what was actually trained and
evaluated on. Run:

    python scripts/paper/make_dataset_table.py
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import torch

logging.basicConfig(level=logging.INFO, format="%(message)s")
log = logging.getLogger("dataset")

# Corpus seeds identify the split: the builder draws train/val/calib/test with
# seeds 1/2/3/4 in that order (configs/data/libero.yaml).
SPLIT_BY_SEED = {1: "train", 2: "val", 3: "calibration", 4: "test"}
ORDER = ["train", "val", "calibration", "test"]


def summarise(path: Path) -> dict:
    d = torch.load(path, map_location="cpu", weights_only=False, mmap=True)
    ex = d["executable"]
    succ = d["succ"].squeeze(-1)
    n_scenes, n_actions = ex.shape
    return {
        "split": SPLIT_BY_SEED.get(int(d["spec"]["seed"]), f"seed{d['spec']['seed']}"),
        "seed": int(d["spec"]["seed"]),
        "scenes": n_scenes,
        "grasps": n_scenes * n_actions,
        "executable": int(ex.sum()),
        "exec_frac": float(ex.float().mean()),
        "succ_rate": float(succ[ex].mean()),
        "objects": len(d["object_names"]),
        "views": int(d["observation"].shape[1]),
        "px": int(d["observation"].shape[-1]),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--corpus_dir", default="results/libero/corpus")
    ap.add_argument("--out", default="paper/tables/tab_dataset.tex")
    args = ap.parse_args()

    rows = [summarise(p) for p in sorted(Path(args.corpus_dir).glob("*.pt"))]
    rows.sort(key=lambda r: ORDER.index(r["split"]) if r["split"] in ORDER else 9)
    total = {k: sum(r[k] for r in rows) for k in ("scenes", "grasps", "executable")}

    body = "\n".join(
        f"{r['split'].capitalize()} & {r['seed']} & {r['scenes']:,} & {r['grasps']:,} & "
        f"{r['executable']:,} & {100 * r['exec_frac']:.1f} & {100 * r['succ_rate']:.1f} \\\\"
        for r in rows
    )
    ref = rows[0]
    tex = f"""% Generated by scripts/paper/make_dataset_table.py -- do not edit by hand.
\\begin{{table}}[t]
\\centering\\small
\\caption{{Grasp corpus. {ref['objects']} HOPE grocery meshes on a table, {ref['views']} RGB-D views per
scene at ${ref['px']}{{\\times}}{ref['px']}$, {rows[0]['grasps'] // rows[0]['scenes']} sampled parallel-jaw grasps per scene, outcome
labels from MuJoCo {{\\tt 3.10.0}} rollouts. A grasp is inexecutable when the open jaws already
intersect the scene; success rate is reported over executable grasps only. Splits are drawn with
disjoint seeds and the calibration split is held disjoint from training, as the conformal
guarantee requires.}}
\\label{{tab:dataset}}
\\begin{{tabular}}{{lrrrrrr}}
\\toprule
Split & Seed & Scenes & Grasps & Executable & Exec.\\ (\\%) & Success (\\%) \\\\
\\midrule
{body}
\\midrule
Total & -- & {total['scenes']:,} & {total['grasps']:,} & {total['executable']:,} & & \\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(tex)
    for r in rows:
        log.info("%-12s seed=%d scenes=%5d grasps=%6d exec=%5.1f%% succ=%5.1f%%",
                 r["split"], r["seed"], r["scenes"], r["grasps"],
                 100 * r["exec_frac"], 100 * r["succ_rate"])
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
