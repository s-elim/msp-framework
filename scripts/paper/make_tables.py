"""Turn results/*.json into LaTeX tables (booktabs) for the manuscript.

    python scripts/paper/make_tables.py --results results/ --out paper/tables/

Every number in every table comes from a JSON file produced by a run that actually happened.
Nothing is typed by hand into the .tex, which is the only way to guarantee the manuscript and
the experiments cannot drift apart.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s")
log = logging.getLogger("tables")

HEADER = (
    "%% AUTO-GENERATED by scripts/paper/make_tables.py -- DO NOT EDIT BY HAND.\n"
    "%% Regenerate with: python scripts/paper/make_tables.py\n"
    "%% Source: {src}\n"
)


def _load(results: Path, name: str):
    p = results / name
    if not p.exists():
        log.warning("SKIP %s (not found)", name)
        return None
    return json.loads(p.read_text())


def table_main(results: Path, out: Path) -> None:
    """Table 1: the headline result at the operating point."""
    rows = _load(results, "e3_coverage.json")
    if not rows:
        return
    r = min(rows, key=lambda x: abs(x["alpha"] - 0.1))  # the alpha = 0.1 operating point

    tex = HEADER.format(src="e3_coverage.json") + rf"""
\begin{{table}}[t]
\centering
\caption{{Calibrated abstention at the $\alpha=0.1$ operating point. Coverage is the
\emph{{marginal}} quantity of Theorem~\ref{{thm:coverage}}, $\Pr(\mathrm{{succ}} \in C(o,a))$,
measured over all test points. Certified precision, $\Pr(\mathrm{{succ}}=1 \mid a \in
\mathcal{{A}}_{{\mathrm{{cert}}}})$, is a different estimand and is reported separately.}}
\label{{tab:main}}
\begin{{tabular}}{{lr}}
\toprule
Quantity & Value \\
\midrule
Target coverage $1-\alpha$          & {r['target_coverage']:.2f} \\
Empirical coverage (Thm.~7)         & \textbf{{{r['coverage']:.3f}}} \\
Certified precision                 & {r['certified_precision']:.3f} \\
Abstention rate                     & {r['abstention_rate']:.3f} \\
Certified action fraction           & {r['certified_fraction']:.3f} \\
Mean ambiguity $\mathbb{{E}}[U(o)]$   & {r['mean_ambiguity']:.4f} \\
\midrule
Rate $R$ [nats]                     & {r['rate']:.3f} \\
Outcome distortion $D$ [nats]       & {r['distortion']:.4f} \\
Test points                         & {r['n_points']:,} \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (out / "tab_main.tex").write_text(tex)
    log.info("wrote tab_main.tex")


