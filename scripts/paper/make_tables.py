def table_libero_ablations(results: Path, out: Path) -> None:
    """Ablations, refereed by within-scene AUC.

    A pooled AUC cannot referee an ablation on this corpus -- a model that has learned only object
    identity still scores ~0.72, so every ablation would look harmless. The `action response' column
    is the std of $s(o,a)$ across a scene's candidate grasps: when it collapses to ~0, the model has
    stopped attending to the action altogether and is emitting one number per scene.
    """
    rows = _load(results, "l6_ablations.json")
    if rows is None:
        return
    body = ""
    for r in rows:
        name = r["ablation"].replace("_", " ")
        bold = name == "full"
        ws = r.get("within_scene_auc", float("nan"))
        pooled = r.get("pooled_auc", float("nan"))
        ar = r.get("action_response_std", float("nan"))
        f = (lambda v: rf"\textbf{{{v:.3f}}}") if bold else (lambda v: f"{v:.3f}")
        body += f"{name} & {f(ws)} & {pooled:.3f} & {ar:.3f} \\\\\n"
    tex = rf"""% AUTO-GENERATED by scripts/paper/make_tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{Ablations, scored by \emph{{within-scene}} AUC. A pooled AUC cannot referee these: on this
corpus a model that has learned nothing but object identity still scores $\approx 0.72$, so every
ablation would look harmless. \emph{{Action response}} is the standard deviation of $s(o,a)$ across a
scene's candidate grasps; when it collapses towards zero the model has stopped attending to the
action and is emitting one number per scene. Note \texttt{{uniform beta}}: placing an equal
multiplier on outcome dimensions whose log-likelihoods live on incommensurate scales starves
$\mathrm{{succ}}$ -- the one outcome the decision rule reads -- and the model stops ranking grasps
entirely.}}
\label{{tab:ablations-libero}}
\begin{{tabular}}{{lccc}}
\toprule
Ablation & Within-scene AUC & Pooled AUC & Action response \\
\midrule
{body}\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (out / "tab_libero_ablations.tex").write_text(tex)
    log.info("wrote tab_libero_ablations.tex")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=Path("results"))
    ap.add_argument("--out", type=Path, default=Path("paper/tables"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    # The LIBERO tables the paper leads with.
    table_proxy_vs_msp(args.results, args.out)
    table_geometry_split(args.results, args.out)
    table_selective(args.results, args.out)
    table_libero_ablations(args.results, args.out)

    # The theory tables.
    table_main(args.results, args.out)
    table_identifiability(args.results, args.out)
    table_ablations(args.results, args.out)
    table_frontier(args.results, args.out)
    table_active(args.results, args.out)
    table_identifiability_per_object(args.results, args.out)
    log.info("tables -> %s", args.out)


if __name__ == "__main__":
    main()
