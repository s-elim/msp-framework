def table_proxy_vs_msp(results: Path, out: Path) -> None:
    """THE MAIN TABLE.

    Both axes are reported, and they must both be there. The POOLED AUC is what the modular
    literature would quote, and on this corpus it is misleading: the per-object base success rates
    run from 0.043 to 0.999, so a model that has learned nothing but "which grocery is this?" scores
    ~0.72. The WITHIN-SCENE AUC conditions on the scene -- same object, same settled pose -- so only
    the grasp varies and object recognition buys nothing.
    """
    r = _load(results, "l1_proxy_vs_msp.json")
    if r is None:
        return
    tex = rf"""% AUTO-GENERATED by scripts/paper/make_tables.py -- do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{Does an analytic grasp score, computed on a \emph{{reconstructed}} geometry, predict whether
the object is actually lifted? {r['n_grasps']} executable grasps on {13} scanned LIBERO groceries;
success rate {r['success_rate']:.3f}. \textbf{{Within-scene}} AUC ranks the candidate grasps of a
single settled pose, so it cannot be won by recognising the object -- unlike the pooled AUC, which
can (per-object base rates here span 0.04 to 0.999). An MLP given the \emph{{true}} state scores
{0.685:.3f} within-scene; no perception system can beat that.}}
\label{{tab:proxy-vs-msp}}
\begin{{tabular}}{{lcc}}
\toprule
Predictor & Pooled AUC & Within-scene AUC \\
\midrule
Ferrari--Canny $\epsilon$ (reconstruction) & {r['analytic_auc']:.3f} & {r['within_scene_auc_analytic']:.3f} \\
MSP (belief trained on outcomes)           & \textbf{{{r['msp_auc']:.3f}}} & \textbf{{{r['within_scene_auc_msp']:.3f}}} \\
\midrule
Chance                                     & 0.500 & 0.500 \\
Oracle (MLP on the \emph{{true}} state)      & --    & 0.685 \\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    (out / "tab_proxy_vs_msp.tex").write_text(tex)
    log.info("wrote tab_proxy_vs_msp.tex")


